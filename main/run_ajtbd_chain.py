from __future__ import annotations

import argparse
import datetime as dt
import re
import zipfile
from pathlib import Path


def read_docx_text(path: Path) -> str:
    with zipfile.ZipFile(path) as zf:
        xml = zf.read("word/document.xml").decode("utf-8", errors="ignore")
    text = re.sub(r"<[^>]+>", "\n", xml)
    text = re.sub(r"\n+", "\n", text)
    return text.strip()


def load_idea(inputs_dir: Path) -> tuple[str, Path]:
    candidates = sorted([*inputs_dir.glob("*.md"), *inputs_dir.glob("*.txt"), *inputs_dir.glob("*.docx")])
    if not candidates:
        raise FileNotFoundError(f"В {inputs_dir} не найдено ни одного файла идеи")
    src = candidates[0]
    if src.suffix.lower() == ".docx":
        return read_docx_text(src), src
    return src.read_text(encoding="utf-8"), src


def write(path: Path, text: str) -> None:
    path.write_text(text.strip() + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="AJTBD chain runner for Here-and-Now")
    parser.add_argument("--project-dir", default=".ajtbd/projects/Here-and-Now")
    args = parser.parse_args()

